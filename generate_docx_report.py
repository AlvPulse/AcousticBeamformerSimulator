def add_heading(doc, text, level):
    heading = doc.add_heading(text, level)
    heading.alignment = WD_ALIGN_PARAGRAPH.RIGHT

def add_paragraph(doc, text, bold=False):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    run = p.add_run(text)
    run.font.name = 'Arial'
    if bold:
        run.bold = True

